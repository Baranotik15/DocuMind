import '@testing-library/jest-dom/vitest'

// jsdom doesn't implement matchMedia; Mantine's MantineProvider reads it
// to detect the OS color scheme.
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
})
